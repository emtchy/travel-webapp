#!/usr/bin/env node
/**
 * Write scripts/migrate-009-london-items.sql from src/sights.js.
 *
 * The London places used to be read straight out of sights.js on every
 * request. They are rows in `items` now, imported once by that migration, and
 * from then on the database is what the app shows — the same as anything the
 * group added. sights.js stays as the template the import came from, and the
 * file this writes is committed, so the import is reviewable and re-runnable
 * (INSERT OR IGNORE: a row already there is left exactly as it is).
 *
 * Re-run this only if you mean to change what a *fresh* database is seeded
 * with. A database that has already imported the London places keeps its own
 * copies; editing sights.js does not reach it, by design.
 *
 *   node scripts/build-items-seed.mjs
 */
import { writeFile } from "node:fs/promises";
import { SIGHTS } from "../src/sights.js";
import { lit } from "./sql-split.mjs";

const OUT = new URL("./migrate-009-london-items.sql", import.meta.url);
const TRIP = 1;

const COLUMNS = [
  "id", "trip_id", "source", "rank", "tier", "name", "name_de", "summary", "summary_de",
  "categories", "area", "station", "cost", "price_label", "price_label_de", "open_on",
  "booking_required", "flags", "url", "wiki", "lat", "lon", "added_by", "added_by_key",
  "created_at",
];

const row = (s) => [
  s.id, TRIP, "builtin", s.rank, s.tier ?? null, s.name, s.name_de ?? null,
  s.summary ?? null, s.summary_de ?? null,
  JSON.stringify(s.categories ?? []), s.area ?? null, s.station ?? null,
  s.cost ?? "free", s.priceLabel ?? null, s.priceLabel_de ?? null,
  JSON.stringify(s.openOn ?? []), s.bookingRequired ? 1 : 0,
  JSON.stringify(s.flags ?? []), s.url ?? null, s.wiki ?? null,
  s.lat ?? null, s.lon ?? null, "setup", "setup", 0,
];

const lines = [
  "-- Generated by scripts/build-items-seed.mjs from src/sights.js. Do not edit by",
  "-- hand; edit the template and re-run the script, or edit the rows in the",
  "-- database. INSERT OR IGNORE: a place already present is left as it is, so a",
  "-- re-run never overwrites a correction someone made in the app.",
  "",
];
for (const s of SIGHTS) {
  lines.push(
    `INSERT OR IGNORE INTO items (${COLUMNS.join(", ")})\n  VALUES (${row(s).map(lit).join(", ")});`);
}
lines.push("");

await writeFile(OUT, lines.join("\n"), "utf8");
console.log(`wrote ${SIGHTS.length} places to ${OUT.pathname.split("/").pop()}`);
